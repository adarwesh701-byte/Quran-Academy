import json,re,sys,collections
T=json.load(open('/home/claude/fusha/tokens.json'))
# Egyptian dialect markers (word-level, Arabic). Boundaries: not preceded/followed by Arabic letter.
A='ء-ي٠-٩ٱ-ۓً-ْٰـ'
W=lambda w: rf'(?<![{A}]){w}(?![{A}])'
words=['مش','ده','دي','دول','إيه','ايه','إزاي','ازاي','ليه','عايز','عايزة','عاوز','عاوزة','عايزين','فين','كده','كدا','بتاع','بتاعة','بتاعك','بتاعتك','بتوعك','دلوقتي','دلوقت','إنت','انت','إنتِ','إنتي','انتي','احنا','إحنا','يلا','أوي','قوي','برّه','بره','جوّه','جوه','علشان','عشان','لسه','لسّه','كمان','تاني','تانية','تانيين','حاجة','حاجات','زي','شوية','شويّة','مفيش','مافيش','معلش','خلاص','بقى','يبقى','أنهي','انهي','أوطي','اوطي','دوس','دوّس','اختار','خد','خدي','ادّي','هات','شوف','شوفي','ابعت','ابعتلي','إمتى','امتى','كام','بقت','بقا','اللي','عالـ','أهو','اهو','برضه','برضو','ساعات','بدل','وريني','ورّيني','فاضل','حلو','يعني','طب','طيب','ماشي','أيوه','ايوه','لأ','مين','إزيك','اتعمل','اتشال','اتحفظ','اتغيّر','اتغير','اتبعت','اتمسح','اتضاف','اتحدث','اتسجل','اتسجّل','اتفتح','اتقفل','اتنشر','خلّي','خلي','عندك','جرّب','ماتنساش','متنساش','لازم']
pat_w=re.compile('|'.join(W(w) for w in words))
# morphological: بيـ/بتـ/بنـ present continuous, هـ/هتـ/هنـ future, ما...ش negation, اتـ passive
pat_m=re.compile(rf'(?<![{A}])(?:[وف]?)(?:بي|بت|بن)[{A}]{{2,}}(?![{A}])|(?<![{A}])(?:[وف]?)(?:هي|هت|هن|هأ)[{A}]{{2,}}(?![{A}])|(?<![{A}])م[اـ]?[{A}]{{2,}}ش(?![{A}])|(?<![{A}])(?:[وف]?)ات[{A}]{{3,}}(?![{A}])')
# words starting with بي/بت/هي/هت that are fusha (avoid false positives)
FUSHA_OK=set('بيت بيتا بيوت بيان بيانات بيع بيئة بين بينما بينهم بيده بيضاء بيض بيروت بتر بتة هيا هيئة هيئات هيكل هيمنة بنت بنات بنك بنود بناء بنفسك بنفسه بنفسها بنية بنجاح بنسبة بنعم بنية هتاف بتول هنا هناك هنالك هند هندسة هندي هنيئا اتصال اتصل اتفاق اتجاه اتباع اتخاذ اتساع اتقان اتحاد اتصالات اتجاهات اتساق اتقن اتهام اتفاقية متاح ماهر ماش ملحوش مرش معاش مغشوش منقوش منفوش نقش رمش عرش فرش'.split())
def hits(t):
    h=[x.group(0) for x in pat_w.finditer(t)]
    for x in pat_m.finditer(t):
        w=x.group(0); core=w.lstrip('وف')
        if core in FUSHA_OK or re.sub('[ً-ْٰ]','',core) in FUSHA_OK: continue
        h.append(w)
    return h
if __name__=='__main__':
    c=collections.Counter(); n=0; tot=0
    for t in T:
        h=hits(t['raw'])
        if h: n+=1; c.update(h)
    print('tokens with markers',n,'of',len(T))
    print(c.most_common(120))
